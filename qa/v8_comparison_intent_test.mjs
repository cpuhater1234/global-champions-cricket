import fs from 'node:fs';
import assert from 'node:assert/strict';
import {loadGame} from './offline_game_host.mjs';
const file=process.env.GCC8_TEST_BUILD||'game/gcc_v8_rendering_clarity.html';
const h=loadGame(file,101,new Map([['gcc_dynasty_v8',fs.readFileSync('qa/stabilisation/fixtures/foundation.json','utf8')]]),{strictIds:true});
const X=h.context.GCC8,s=h.G.state;
assert(X.dispatch('continue',[]));X.G.go('team');X.ui.view='team';X.render();
const p=X.roster().find(p=>p.role==='WK-BAT');assert(p);
const truth=()=>JSON.stringify({teams:s.teams,xi:s.xi,order:s.battingOrder,seed:s.seed});const before=truth();
assert(X.dispatch('comparePlayers',[p.id]));
assert.equal(X.ui.compareTarget,null,'opening comparison must not invent an alternative');
assert(!h.get('g8dialogContent').innerHTML.includes('g8compareidentities'),'no rating verdict before explicit choice');
assert(h.get('g8dialogContent').innerHTML.includes('Choose a player'),'explicit unselected prompt');
const q=X.comparisonCandidates(p.id).find(q=>q.role==='BOWL');assert(q);
assert(X.dispatch('comparePlayers',[p.id,q.id]));
assert(h.get('g8dialogContent').innerHTML.includes('Different squad roles'),'cross-role comparison does not masquerade as keeper alternatives');
assert.equal(before,truth(),'comparison cannot change career or random state');
assert(!X.dispatch('comparePlayers',[p.id,p.id]));
assert(!X.dispatch('comparePlayers',[p.id,999999]));
assert(X.dispatch('comparePlayers',[p.id]));assert.equal(X.ui.compareTarget,null,'reopening clears stale second player');
assert.equal(h.errors.length,0);console.log('Comparison intent: all assertions passed; VM commands only.');
