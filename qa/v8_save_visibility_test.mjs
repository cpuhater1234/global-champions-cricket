import fs from 'node:fs';
import assert from 'node:assert/strict';
import {loadGame} from './offline_game_host.mjs';
const h=loadGame(process.env.GCC8_TEST_BUILD||'game/gcc_v8_product_candidate.html',101,new Map([['gcc_dynasty_v8',fs.readFileSync('qa/stabilisation/fixtures/foundation.json','utf8')]]),{strictIds:true});
const X=h.context.GCC8;
assert(X.dispatch('continue'));
const storage=h.context.localStorage, original=storage.setItem;
storage.setItem=()=>{throw new Error('simulated quota failure');};
assert(X.dispatch('how'));
assert(h.get('g8dialogFeedback').textContent.includes('could not save'));
assert.equal(X.dispatch('unknown-command'),false);
assert(h.get('g8hud').innerHTML.includes('Progress not saved'),'save failure stays visible when ordinary feedback changes');
assert(X.dispatch('close'));
assert(h.get('g8hud').innerHTML.includes('Progress not saved'));
storage.setItem=original;
assert(X.dispatch('how'));
assert(!h.get('g8hud').innerHTML.includes('Progress not saved'),'only a successful save clears persistent warning');
assert(h.errors.every(e=>String(e).includes('simulated quota failure')),JSON.stringify(h.errors));
console.log('Persistent save warning and recovery passed.');
