import assert from 'node:assert/strict';
import fs from 'node:fs';
import {loadGame} from '../offline_game_host.mjs';
import {startDraft,finishDraft,selectManualXI} from '../club-expansion-20261027/helpers.mjs';
const h=loadGame('qa/perfection-20261030/candidate.html',101,new Map(),{strictIds:true});
const X=h.context.GCC8,s=h.G.state;
startDraft(h);finishDraft(h);selectManualXI(h);h.G.startSeason();X.ui.view='season';
assert(X.dispatch('watchNext'));
assert.equal(X.ui.match.preMatch,true,'new watched match stops at the batting-order reveal');
assert.equal(X.ui.match.running,false,'no ball timer runs behind the reveal');
assert.equal(X.ui.match.count,0);
const r=X.ui.result,cricketBefore=JSON.stringify({results:s.results,stats:s.playerSeasonStats});
let html=X.views.matchReveal();
assert.match(html,/The toss/);
assert(html.includes(X.battingOrderNote(r)));
assert.match(html,/data-action="startPlayback"/);
assert.doesNotMatch(html,/LATEST DELIVERY|bowl first/,'no premature deliveries or redundant opponent instruction');
assert(X.dispatch('startPlayback'));
assert.equal(X.ui.match.preMatch,false);assert.equal(X.ui.match.running,true);assert.equal(X.ui.match.count,0);
assert.doesNotMatch(X.views.matchReveal(),/data-action="startPlayback"/);
assert.equal(JSON.stringify({results:s.results,stats:s.playerSeasonStats}),cricketBefore,'starting playback does not simulate another match');
X.ui.match.count=12;X.ui.match.running=false;delete X.ui.match.preMatch;
assert.doesNotMatch(X.views.matchReveal(),/data-action="startPlayback"/,'older saved playback bypasses reveal');
assert.equal(X.ui.match.count,12);
assert(X.dispatch('matchSkip'));assert.equal(X.ui.match,null);assert(X.dispatch('watchMatch'));assert.equal(X.ui.match.preMatch,true,'explicit replay includes opening acknowledgement');assert(X.dispatch('matchSkip'));assert.equal(JSON.stringify({results:s.results,stats:s.playerSeasonStats}),cricketBefore,'skipping and replay never resimulate');
assert.deepEqual(h.errors,[]);
const checks={pass:true,checks:['new match waits before first ball','truthful batting order','start continues existing match','old playback resumes unchanged']};
fs.writeFileSync('qa/perfection-20261030/prematch-contracts.json',JSON.stringify(checks,null,2));console.log(checks);
